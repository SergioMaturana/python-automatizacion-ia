frutas = ["manzana", "pera", "uva"]

print(frutas)           # ['manzana', 'pera', 'uva']
print(frutas[0])         # "manzana" (primer elemento, índice 0)
print(frutas[1])         # "pera"
print(frutas[-1])        # "uva" (índice negativo = desde el final)
print(len(frutas))       # 3 (cuántos elementos tiene)